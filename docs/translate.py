def build() -> None:
    source = (HERE / "index.html").read_text(encoding="utf-8")
    missing = [en for en, *_ in TEXTS if en not in source]
    if missing:
        raise SystemExit("These English texts are no longer in index.html; update TEXTS:\n  " + "\n  ".join(missing))
    for i, (name, lang) in enumerate(LANGS.items(), start=1):
        page = source.replace('<html lang="en">', f'<html lang="{lang}">')
        page = page.replace('hreflang="en" aria-current="page"', 'hreflang="en"')
        page = page.replace(f'hreflang="{lang}">', f'hreflang="{lang}" aria-current="page">')
        for texts in TEXTS:
            page = page.replace(texts[0], texts[i])
        (HERE / f"{name}.html").write_text(page, encoding="utf-8")
        print(f"wrote {name}.html")


if __name__ == "__main__":
    build()
